// Inventory the installed production dependency set, including PDF.js asset notices.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const hash = value => createHash('sha256').update(value).digest('hex');
const read = path => readFileSync(path, 'utf8');
const lock = JSON.parse(read('package-lock.json'));
const supplemental = {
  'js-tiktoken': 'third_party/supplemental/js-tiktoken-LICENSE',
  saxes: 'third_party/supplemental/saxes-LICENSE',
  'abstract-logging': 'third_party/supplemental/abstract-logging-LICENSE',
  'fs-ext-extra-prebuilt': 'third_party/supplemental/fs-ext-extra-prebuilt-LICENSE.txt',
};
const packages = [], absentOptional = [];
let notices = 'TsLightRAG — installed production dependency notices\n\n'
  + 'Generated by node scripts/licenses.mjs --write. Scope and supplemental sources: NOTICE.md.\n'
  + 'Package license labels do not replace the full asset license texts below.\n';
for (const [path, entry] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b, 'en'))) {
  if (!path.includes('node_modules/') || entry.dev || entry.link) continue;
  if (!existsSync(`${path}/package.json`)) {
    if (!entry.optional) throw new Error(`Missing production dependency: ${path}`);
    absentOptional.push(path); continue;
  }
  const pkg = JSON.parse(read(`${path}/package.json`));
  if (pkg.version !== entry.version) throw new Error(`Version mismatch: ${path}`);
  let files = readdirSync(path).filter(name => /^(licen[cs]e|copying|notice|copyright)(\.|$|-)/i.test(name))
    .map(name => `${path}/${name}`).filter(file => statSync(file).isFile());
  if (pkg.name === 'pdfjs-dist') {
    for (const directory of ['cmaps', 'iccs', 'standard_fonts', 'wasm']) {
      files.push(...readdirSync(`${path}/${directory}`).filter(name => /^(license|notice)/i.test(name))
        .map(name => `${path}/${directory}/${name}`));
    }
  }
  if (!files.length && supplemental[pkg.name]) files = [supplemental[pkg.name]];
  if (!files.length && pkg.name.startsWith('@napi-rs/canvas-')) files = ['node_modules/@napi-rs/canvas/LICENSE'];
  if (!files.length) throw new Error(`Missing license text: ${path}`);
  const license = pkg.license ?? pkg.licenses?.map(item => item.type).join(' OR ') ?? entry.license;
  if (!license) throw new Error(`Missing declared license: ${path}`);
  const texts = files.sort().map(source => ({ source, sha256: hash(readFileSync(source)) }));
  packages.push({ path, name: pkg.name, version: pkg.version, license, texts });
  notices += `\n${'='.repeat(72)}\n${pkg.name}@${pkg.version} (${license})\n${path}\n`;
  for (const { source } of texts) notices += `\n--- ${source} ---\n${read(source).replace(/[ \t]+$/gm, '').trimEnd()}\n`;
}
const manifest = JSON.stringify({ scope: 'installed production dependencies; Linux x64 onboarding installation',
  packageLockSha256: hash(readFileSync('package-lock.json')), packages, absentOptional }, null, 2) + '\n';
for (const [path, content] of [['third_party/dependencies.json', manifest], ['third_party/THIRD_PARTY_NOTICES.txt', notices]]) {
  if (process.argv.includes('--write')) writeFileSync(path, content);
  else if (!existsSync(path) || read(path) !== content) throw new Error(`Outdated notices: ${resolve(path)}`);
}
console.log(`Licenses verified: ${packages.length} installed production packages; ${absentOptional.length} absent optional packages recorded.`);
